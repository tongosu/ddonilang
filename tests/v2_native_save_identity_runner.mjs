import assert from 'node:assert/strict';
import {createProjectNavigation} from '../solutions/seamgrim_ui_mvp/ui/workbench/project_navigation.js';
import {createEditRecoveryGuard} from '../solutions/seamgrim_ui_mvp/ui/workbench/persistence/edit_recovery_guard.js';

const store=new Map();
const storage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)};
globalThis.localStorage=storage;
let source={project_id:'draft-A',profile:'v25',files:[{path:'main.ddn',text:'A'}]};
let notice;
const state={myWorkRows:[]};
const nav=createProjectNavigation({state,els:{},MY_WORK_INDEX_KEY:'my-work',currentProject:()=>({title:'同名'})});
nav.rememberMyWorkProject({projectId:'draft-A',title:'동명',source:'local_only'});
nav.rememberMyWorkProject({projectId:'draft-B',title:'동명',source:'local_only'});
nav.rememberMyWorkProject({projectId:'saved-A',title:'동명',source:'native_source',nativeLocator:'{}',replacesLocalProjectId:'draft-A'});
assert.equal(nav.readMyWorkIndex().find(r=>r.project_id==='draft-A').native_saved_as,'saved-A');
assert.equal(nav.readMyWorkIndex().find(r=>r.project_id==='draft-B').native_saved_as,undefined);
assert.equal(nav.readMyWorkIndex().length,3,'Recovery index bytes must not be deleted');
const guard=createEditRecoveryGuard({storage,capture:()=>structuredClone(source),applyDraft:()=>{},present:n=>notice=n});
guard.saveEditor('main.ddn','A');guard.beginSave(1);
source={project_id:'draft-B',profile:'v25',files:[{path:'main.ddn',text:'B'}]};
guard.saved(1);
const key='seamgrim.workbench.edit_draft.b2-provisional-1:'+encodeURIComponent('draft-A');
assert.equal(JSON.parse(store.get(key)).pending,false);
assert.equal(JSON.parse(store.get(key)).source.files[0].text,'A');
assert.equal(notice.visible,false,'Saved former project should no longer offer pending recovery');
source.project_id='draft-A';source.files[0].text='A';
guard.saveEditor('main.ddn','A');guard.beginSave(2);
guard.saveEditor('main.ddn','NEW');source.files[0].text='NEW';guard.saved(2);
assert.equal(JSON.parse(store.get(key)).pending,true,'Newer edit survives old completion');
assert.equal(JSON.parse(store.get(key)).source.files[0].text,'NEW');
console.log(JSON.stringify({cases:4,status:'PASS_AUTHOR_COMPONENT',browser:'NOT_RUN',nativeCold:'NOT_RUN'}));
