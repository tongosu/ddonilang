import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({headless:true, executablePath:"C:/Program Files/Google/Chrome/Application/chrome.exe"});
try {
  const page = await browser.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(String(error)));
  await page.goto(process.env.DDN_TEST_URL || "http://127.0.0.1:8790/");
  await page.waitForFunction(() => window.__SEAMGRIM_APPROVED_WORKBENCH__?.getSnapshot().readiness.source);
  const original = await page.locator("#source-editor").inputValue();
  await page.locator("#source-editor").fill("값 := 0. { 참 }인 동안 { 값 <- 값 + 1. }.");
  await page.getByTestId("lifecycle-run").click();
  await page.waitForFunction(() => document.querySelector('[data-testid="run-status"]').textContent === "실행 중");
  assert.equal(await page.getByTestId("lifecycle-stop").isEnabled(), true);
  await page.waitForFunction(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot().executionLifecycle?.final_status === "stopped", null, {timeout:20000}).catch(async error => {
    console.log(JSON.stringify(await page.evaluate(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot()))); throw error;
  });
  const stopped = await page.evaluate(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot());
  assert.ok(await page.getByTestId("host-stop-notice").isVisible());
  assert.match(await page.getByTestId("run-status").innerText(), /실행 중지/);
  assert.match(await page.getByTestId("host-stop-notice").innerText(), /10초.*반복이 끝나는 조건/);
  assert.equal(stopped.activeFrame, null);
  assert.equal(stopped.diagnostics.some(d => d.severity === "error"), false);
  assert.doesNotMatch(JSON.stringify(stopped.runs), /10초|HOST_STEP|timeout|"failed"/);
  const longSimulation = original.replace(/마디수\s*:\s*\d+/, "마디수: 100000");
  assert.notEqual(longSimulation, original);
  await page.locator("#source-editor").fill(longSimulation);
  await page.getByTestId("lifecycle-run").click();
  await page.waitForFunction(() => document.querySelector('[data-testid="approved-workbench-root"]').dataset.executionState === "running");
  await page.waitForTimeout(11000);
  assert.equal(await page.getByTestId("approved-workbench-root").getAttribute("data-execution-state"), "running");
  assert.equal(await page.getByTestId("host-stop-notice").isVisible(), false);
  await page.getByTestId("lifecycle-stop").click();
  await page.waitForFunction(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot().executionLifecycle.final_status === "stopped");
  assert.match(await page.getByTestId("run-status").innerText(), /실행 중지/);
  const blockedLater = original.replace("(매마디)마다 {", "(매마디)마다 { { t >= 2 }인것 일때 { { 참 }인 동안 {}. }.");
  assert.notEqual(blockedLater, original);
  await page.locator("#source-editor").fill(blockedLater);
  await page.getByTestId("lifecycle-run").click();
  await page.waitForFunction(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot().executionLifecycle.status === "running");
  await page.waitForFunction(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot().executionLifecycle.final_status === "stopped", null, {timeout:20000});
  const lateStop = await page.evaluate(() => window.__SEAMGRIM_APPROVED_WORKBENCH__.getSnapshot());
  const lastRun = lateStop.runs.at(-1);
  assert.equal(lastRun.frame_count, 2, "blocked third madi must not create a frame");
  assert.equal(lastRun.final_status, "stopped");
  assert.equal(lateStop.diagnostics.some(d => d.severity === "error"), false);
  assert.doesNotMatch(JSON.stringify(lastRun), /10초|HOST_STEP|timeout|"failed"/);
  assert.deepEqual(errors, []);
  console.log("HOST_STOP_BROWSER_PASS actual_10s_stop=1 no_error_or_frame=1 live_over_10s=1 blocked_third_madi_preserves_two_frames=1");
} finally { await browser.close(); }
